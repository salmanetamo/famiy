-- 000003_auth: accounts and server-side sessions (ADR-004).
-- The person.owner_user_id column and the same_owner link rule arrive in 000004.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stored already trimmed and lower-cased by the application; the CHECK keeps
    -- it that way, so a plain UNIQUE index gives case-insensitive uniqueness.
    email         TEXT        NOT NULL,
    password_hash TEXT        NOT NULL,   -- PHC-format argon2id string
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT email_normalized CHECK (email = lower(btrim(email))),
    CONSTRAINT email_length     CHECK (char_length(email) BETWEEN 3 AND 254),
    CONSTRAINT app_user_email_key UNIQUE (email)
);

-- Only the SHA-256 of the session token is stored, so a database leak does not
-- hand out live sessions.
CREATE TABLE session (
    token_hash BYTEA       PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT token_hash_is_sha256 CHECK (octet_length(token_hash) = 32)
);

CREATE INDEX idx_session_user    ON session (user_id);
CREATE INDEX idx_session_expires ON session (expires_at);
