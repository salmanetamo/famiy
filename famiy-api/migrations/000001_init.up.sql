-- 000001_init: kinship model (ported from PoC-1; see ADR-001).
--   * Kinship is a DAG: the atomic edge is parent -> child, up to two parents.
--   * Partnership is a separate, undirected edge type.
--   * Siblings and genealogical distance are derived by traversal, never stored.

CREATE TABLE person (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    given_name   TEXT        NOT NULL,
    family_name  TEXT,
    birth_date   DATE,
    birth_approx BOOLEAN     NOT NULL DEFAULT FALSE, -- "approximate date" requirement
    death_date   DATE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT given_name_not_blank CHECK (btrim(given_name) <> ''),
    CONSTRAINT death_not_before_birth
        CHECK (birth_date IS NULL OR death_date IS NULL OR death_date >= birth_date)
);

-- Atomic kinship edge: one row per (parent, child).
CREATE TABLE parent_child (
    parent_id BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    child_id  BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    PRIMARY KEY (parent_id, child_id),
    CONSTRAINT no_self_parent CHECK (parent_id <> child_id)
);

-- Partnership edge (marriage/union). Undirected; stored canonically as (a < b)
-- so (a,b) and (b,a) can never both exist.
CREATE TABLE partnership (
    partner_a BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    partner_b BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    kind      TEXT   NOT NULL DEFAULT 'marriage',
    PRIMARY KEY (partner_a, partner_b),
    CONSTRAINT partner_order CHECK (partner_a < partner_b)
);

-- One index per traversal direction (PK already covers parent_id-first lookups
-- for the (parent_id, child_id) pair, but idx_pc_parent keeps "walk DOWN" explicit).
CREATE INDEX idx_pc_child       ON parent_child (child_id);   -- walk UP   (child -> parents)
CREATE INDEX idx_pc_parent      ON parent_child (parent_id);  -- walk DOWN (parent -> children)
CREATE INDEX idx_partnership_b  ON partnership  (partner_b);  -- partner lookup from the b side

-- Invariant: at most two parents per child. A CHECK can't count rows, so a
-- BEFORE INSERT trigger does. Unlike PoC-1, it first locks the child's person
-- row so two concurrent inserts for the same child serialize instead of both
-- seeing "1 parent" and both succeeding.
CREATE FUNCTION enforce_max_two_parents() RETURNS TRIGGER AS $$
BEGIN
    PERFORM 1 FROM person WHERE id = NEW.child_id FOR UPDATE;
    -- An exact duplicate edge is the primary key's error to report ("already
    -- exists"), not ours ("too many parents"), so step aside.
    IF EXISTS (SELECT 1 FROM parent_child
               WHERE parent_id = NEW.parent_id AND child_id = NEW.child_id) THEN
        RETURN NEW;
    END IF;
    IF (SELECT count(*) FROM parent_child WHERE child_id = NEW.child_id) >= 2 THEN
        RAISE EXCEPTION 'person % already has two parents', NEW.child_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_max_two_parents
    BEFORE INSERT ON parent_child
    FOR EACH ROW EXECUTE FUNCTION enforce_max_two_parents();

