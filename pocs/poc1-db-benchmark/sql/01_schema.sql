-- PoC-1 schema — Family Graph kinship model (PostgreSQL 14+)
--
-- Design decisions (see ADR-001 and 01—PRODUCT_REQUIREMENTS.md):
--   * Kinship is a DAG, not a tree: the atomic edge is parent -> child, and a
--     child may have up to two parents.
--   * Partnership is a SEPARATE, undirected edge type.
--   * Siblings and genealogical distance are DERIVED by traversal, never stored.
--
-- Re-running this file wipes and recreates the three tables, so it doubles as
-- the "reset" step between benchmark scales.

DROP TABLE IF EXISTS parent_child CASCADE;
DROP TABLE IF EXISTS partnership CASCADE;
DROP TABLE IF EXISTS person      CASCADE;

CREATE TABLE person (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    given_name   TEXT    NOT NULL,
    family_name  TEXT,
    sex          CHAR(1),                       -- 'M' | 'F' | 'X' | NULL (only shapes synthetic data)
    birth_date   DATE,
    birth_approx BOOLEAN NOT NULL DEFAULT FALSE, -- models "approximate date" requirement
    death_date   DATE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Atomic kinship edge: one row per (parent, child).
CREATE TABLE parent_child (
    parent_id BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    child_id  BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    PRIMARY KEY (parent_id, child_id),
    CONSTRAINT no_self_parent CHECK (parent_id <> child_id)
);

-- Partnership edge (marriage/union). Undirected; stored canonically as (a < b)
-- so (a,b) and (b,a) can never both exist.
CREATE TABLE partnership (
    partner_a BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    partner_b BIGINT NOT NULL REFERENCES person(id) ON DELETE CASCADE,
    kind      TEXT   NOT NULL DEFAULT 'marriage',
    PRIMARY KEY (partner_a, partner_b),
    CONSTRAINT partner_order CHECK (partner_a < partner_b)
);

-- The two indexes that make recursive traversal cheap: one for each direction.
CREATE INDEX idx_pc_child  ON parent_child (child_id);    -- walk UP   (child -> parents)
CREATE INDEX idx_pc_parent ON parent_child (parent_id);   -- walk DOWN (parent -> children)
CREATE INDEX idx_partnership_b ON partnership (partner_b);-- partner lookup from the b side

-- Invariant: at most two parents per child. A CHECK can't count rows, so we use
-- a BEFORE INSERT trigger. (It fires per row, so the loader disables it around
-- the bulk COPY and re-enables it afterwards — see generate.py.)
CREATE OR REPLACE FUNCTION enforce_max_two_parents() RETURNS TRIGGER AS $$
BEGIN
    IF (SELECT count(*) FROM parent_child WHERE child_id = NEW.child_id) >= 2 THEN
        RAISE EXCEPTION 'person % already has two parents', NEW.child_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_max_two_parents
    BEFORE INSERT ON parent_child
    FOR EACH ROW EXECUTE FUNCTION enforce_max_two_parents();

